class Diagram(BaseDiagram):
    """Wrap authored labels using the same locally installed font as the reader."""
    @staticmethod
    def lines(text,width,size):
        font=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',size)
        result=[]
        for line in text.split('\n'):
            current=''
            for word in line.split():
                candidate=(current+' '+word).strip()
                if current and font.getlength(candidate)>width:
                    result.append(current);current=word
                else:current=candidate
            result.append(current)
        return result
    def text(self,x,y,text,size=17,color='#173644'):
        return super().text(x,y,'\n'.join(self.lines(text,self.w-x-24,size)),size,color)
    def box(self,x,y,w,h,text,color='#e4edf7',size=17):
        while True:
            lines=self.lines(text,w-28,size)
            if 30+(len(lines)-1)*(size+7)<=h-7 or size<=12:break
            size-=1
        self.items.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" fill="{color}" stroke="#6c849d"/>')
        BaseDiagram.text(self,x+14,y+27,'\n'.join(lines),size)

def flow(d,x,y,w,labels,color='#e4edf7'):
    for i,s in enumerate(labels):
        d.box(x,y+130*i,w,90,s,color,size=17)
        if i:d.arrow([(x+w/2,y+(i-1)*130+90),(x+w/2,y+i*130)])

