    d.box(35,100,360,120,input_label,size=18)
    d.box(530,100,690,90,'Вход блока H [B,L,D]\nПовторить N блоков; параметры по конфигурации',size=18)
    d.arrow([(395,160),(530,160)])
    attn,mlp,norm=block
    d.box(530,300,690,100,attn,size=18)
    d.box(530,490,690,75,('Сложить с H → Y' if pre else 'Сложить с H → LayerNorm → Y'),color='#e3f2e7',size=19)
    d.box(530,650,690,100,mlp,size=18)
    d.box(530,835,690,75,('Сложить с Y → выход блока' if pre else 'Сложить с Y → LayerNorm → выход блока'),color='#e3f2e7',size=19)
    d.arrow([(875,190),(875,300)]);d.arrow([(875,400),(875,490)])
    d.arrow([(875,565),(875,650)]);d.arrow([(875,750),(875,835)])
    d.arrow([(530,145),(465,145),(465,528),(530,528)])
    d.arrow([(530,528),(425,528),(425,872),(530,872)])
    d.text(35,340,'H: обход преобразования',17);d.text(35,700,'Y: второй обход',17)
    d.box(35,800,360,110,output,color='#fff1d7',size=17)
