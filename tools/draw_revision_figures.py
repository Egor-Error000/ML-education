class Diagram:
    def __init__(self,title,desc,w=1120,h=720):
        self.w=w;self.h=h
        self.items=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" role="img" aria-labelledby="title desc"><title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>',
        '<defs><marker id="arrow" markerWidth="9" markerHeight="9" refX="8" refY="4.5" orient="auto"><path d="M0,0 L9,4.5 L0,9" fill="#315a67"/></marker></defs>',f'<rect width="{w}" height="{h}" fill="#f7f9fc"/>']
        self.text(28,35,title,23)
    def text(self,x,y,text,size=17,color='#173644'):
        lines=text.split('\n')
        self.items.append(f'<text x="{x}" y="{y}" font-family="Segoe UI,Arial,sans-serif" font-size="{size}" fill="{color}">'+''.join(f'<tspan x="{x}" dy="{0 if i==0 else size+7}">{escape(line)}</tspan>' for i,line in enumerate(lines))+'</text>')
    def box(self,x,y,w,h,text,color='#e4edf7',size=17):
        self.items.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" fill="{color}" stroke="#6c849d"/>')
        self.text(x+14,y+27,text,size)
    def arrow(self,points,label=None):
        d='M'+' L'.join(f'{x},{y}' for x,y in points)
        self.items.append(f'<path d="{d}" fill="none" stroke="#315a67" stroke-width="2" marker-end="url(#arrow)"/>')
        if label:self.text(points[0][0]+6,points[0][1]-8,label,14)
    def save(self,name):(OUT/name).write_text('\n'.join(self.items)+ '</svg>\n',encoding='utf8',newline='\n')
